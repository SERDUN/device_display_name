// Regenerates lib/src/apple_identifiers.g.dart:
//
//   dart run tool/apple_identifiers/generate.dart
//
// Source: the iOS list of github.com/kyle-seongwoo-jun/apple-device-identifiers
// (MIT, iPhone, iPad and iPod touch), with overrides.json on top for devices
// the list does not have yet. Commit the result; the build never downloads it.

import 'dart:convert';
import 'dart:io';

const _source =
    'https://raw.githubusercontent.com/kyle-seongwoo-jun/apple-device-identifiers/main/ios-device-identifiers.json';

Future<void> main() async {
  final root = File.fromUri(Platform.script).parent.parent.parent;
  final client = HttpClient();
  final Map<String, Object?> upstream;
  try {
    final response = await (await client.getUrl(Uri.parse(_source))).close();
    if (response.statusCode != 200) {
      throw HttpException(
        'HTTP ${response.statusCode}',
        uri: Uri.parse(_source),
      );
    }
    upstream = jsonDecode(
      await response.transform(utf8.decoder).join(),
    ) as Map<String, Object?>;
  } finally {
    client.close();
  }

  final overrides = jsonDecode(
    File('${root.path}/tool/apple_identifiers/overrides.json')
        .readAsStringSync(),
  ) as Map<String, Object?>;

  final names = <String, String>{
    for (final MapEntry(:key, :value) in upstream.entries)
      if (value is String && _isDevice(key)) key: value,
    for (final MapEntry(:key, :value) in overrides.entries)
      if (value is String && !key.startsWith('_')) key: value,
  };
  final keys = names.keys.toList()..sort(_byIdentifier);

  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/apple_identifiers/generate.dart - do not edit.',
    )
    ..writeln(
      '// Source: github.com/kyle-seongwoo-jun/apple-device-identifiers (MIT) and overrides.json.',
    )
    ..writeln()
    ..writeln('/// Marketing names of Apple devices by hardware identifier.')
    ..writeln('const Map<String, String> appleIdentifiers = {');
  for (final key in keys) {
    out.writeln(
      "  '$key': '${names[key]!.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}',",
    );
  }
  out.writeln('};');

  File('${root.path}/lib/src/apple_identifiers.g.dart')
      .writeAsStringSync(out.toString());
  stdout.writeln('${keys.length} identifiers');
}

final _identifier = RegExp(r'^(iPhone|iPad|iPod)(\d+),(\d+)$');

bool _isDevice(String key) => _identifier.hasMatch(key);

int _byIdentifier(String a, String b) {
  final ma = _identifier.firstMatch(a)!, mb = _identifier.firstMatch(b)!;
  final family = ma[1]!.compareTo(mb[1]!);
  if (family != 0) return family;
  final major = int.parse(ma[2]!).compareTo(int.parse(mb[2]!));
  if (major != 0) return major;
  return int.parse(ma[3]!).compareTo(int.parse(mb[3]!));
}
